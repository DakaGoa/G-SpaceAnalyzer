# Builds dist\GSpaceAnalyzerSetup.exe - a single self-contained installer.
#
# Uses the C# compiler that ships with the .NET Framework, so no extra
# tooling (Inno Setup, NSIS, WiX) needs to be installed. The release binary is
# embedded as a resource, as is the application icon.
#
#   powershell -ExecutionPolicy Bypass -File installer\build-installer.ps1
#   powershell -ExecutionPolicy Bypass -File installer\build-installer.ps1 -SkipAppBuild

param(
    [switch]$SkipAppBuild,
    # Code signing is optional: supply a .pfx and the app and the setup are both
    # signed (the app first, because the setup embeds it). Env vars are used when
    # the parameters are omitted, which is how CI passes the certificate.
    [string]$PfxPath = $env:CODESIGN_PFX,
    [string]$PfxPassword = $env:CODESIGN_PFX_PASSWORD,
    [string]$TimestampUrl = 'http://timestamp.digicert.com'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot

function Find-SignTool {
    $onPath = Get-Command signtool.exe -ErrorAction SilentlyContinue
    if ($onPath) { return $onPath.Source }

    $kits = @("${env:ProgramFiles(x86)}\Windows Kits\10\bin",
              "$env:ProgramFiles\Windows Kits\10\bin")
    foreach ($kit in $kits) {
        if (-not (Test-Path $kit)) { continue }
        $found = Get-ChildItem $kit -Recurse -Filter signtool.exe -ErrorAction SilentlyContinue |
            Where-Object { $_.DirectoryName -match '\\x64$' } |
            Sort-Object FullName -Descending |
            Select-Object -First 1
        if ($found) { return $found.FullName }
    }
    return $null
}

$signTool = $null
if ($PfxPath) {
    if (-not (Test-Path $PfxPath)) { throw "Signing certificate not found: $PfxPath" }
    $signTool = Find-SignTool
    if (-not $signTool) {
        throw 'Cannot sign: signtool.exe was not found. Install the Windows SDK or add it to PATH.'
    }
    Write-Host "Signing with $PfxPath"
}

function Invoke-Sign([string]$File) {
    if (-not $signTool) { return }

    $arguments = @('sign', '/fd', 'SHA256', '/d', 'G-SpaceAnalyzer',
                   '/du', 'https://github.com/DakaGoa/G-SpaceAnalyzer',
                   '/f', $PfxPath)
    if ($PfxPassword) { $arguments += @('/p', $PfxPassword) }
    if ($TimestampUrl) { $arguments += @('/tr', $TimestampUrl, '/td', 'SHA256') }
    $arguments += $File

    & $signTool @arguments
    if ($LASTEXITCODE -ne 0) { throw "Signing failed for $File" }

    & $signTool verify /pa $File | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "Signature verification failed for $File" }
    Write-Host ("Signed {0}" -f (Split-Path -Leaf $File))
}

Push-Location $root
try {
    if (-not $SkipAppBuild) {
        Write-Host 'Building the release binary...'
        cargo build --release
        if ($LASTEXITCODE -ne 0) { throw 'cargo build --release failed.' }
    }

    $app = Join-Path $root 'target\release\G-SpaceAnalyzer.exe'
    if (-not (Test-Path $app)) {
        throw "Missing $app - run a release build first."
    }

    # The setup carries the app as a resource, so the payload is signed first.
    Invoke-Sign $app

    $csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
    if (-not (Test-Path $csc)) {
        throw "C# compiler not found at $csc"
    }

    $dist = Join-Path $root 'dist'
    New-Item -ItemType Directory -Force -Path $dist | Out-Null

    # Keep one source of truth for the version: read it from Cargo.toml and
    # emit a tiny C# file the installer compiles against.
    $cargoToml = Get-Content (Join-Path $root 'Cargo.toml') -Raw
    $versionMatch = [regex]::Match($cargoToml, '(?m)^\s*version\s*=\s*"([^"]+)"')
    if (-not $versionMatch.Success) { throw 'Could not read the version from Cargo.toml.' }
    $version = $versionMatch.Groups[1].Value
    $buildInfo = Join-Path $root 'installer\BuildInfo.cs'
    # csc turns these assembly attributes into the setup exe's Win32 version
    # resource, which is what Explorer's file properties reads.
    $parts = @($version.Split('.'))
    while ($parts.Count -lt 4) { $parts += '0' }
    $fourPart = $parts[0..3] -join '.'

    $buildInfoText = @"
// Generated by installer\build-installer.ps1 from Cargo.toml. Do not edit.
using System.Reflection;

[assembly: AssemblyTitle("G-SpaceAnalyzer Setup")]
[assembly: AssemblyDescription("G-SpaceAnalyzer installer")]
[assembly: AssemblyProduct("G-SpaceAnalyzer")]
[assembly: AssemblyCompany("G-SpaceAnalyzer")]
[assembly: AssemblyCopyright("MIT License")]
[assembly: AssemblyVersion("$fourPart")]
[assembly: AssemblyFileVersion("$fourPart")]
[assembly: AssemblyInformationalVersion("$version")]

namespace GSpaceAnalyzerSetup
{
    internal static class BuildInfo
    {
        internal const string Version = "$version";
    }
}
"@
    Set-Content -Path $buildInfo -Value $buildInfoText -Encoding ASCII
    Write-Host ("Version {0}" -f $version)

    $icon = Join-Path $root 'assets\icons\icon.ico'
    $output = Join-Path $dist 'GSpaceAnalyzerSetup.exe'

    $cscArgs = @(
        '/nologo'
        '/target:winexe'
        '/optimize+'
        '/codepage:65001'
        "/win32icon:$icon"
        "/resource:$icon,AppIcon"
        "/resource:$app,Payload"
        "/out:$output"
        (Join-Path $root 'installer\GSpaceAnalyzerSetup.cs')
        $buildInfo
        '/r:System.dll'
        '/r:System.Drawing.dll'
        '/r:System.Windows.Forms.dll'
    )

    Write-Host 'Compiling the installer...'
    & $csc $cscArgs
    if ($LASTEXITCODE -ne 0) { throw 'Installer compilation failed.' }

    Invoke-Sign $output

    $item = Get-Item $output
    Write-Host ''
    Write-Host ("Built {0} ({1:N2} MB)" -f $item.FullName, ($item.Length / 1MB))
    if (-not $signTool) {
        Write-Host 'Unsigned: set CODESIGN_PFX (and CODESIGN_PFX_PASSWORD) to sign the build.'
    }
}
finally {
    Pop-Location
}
